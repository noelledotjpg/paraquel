import fs from "fs";
import path from "path";

const ROOT = path.resolve("assets/pages");
const OUTPUT = path.join(ROOT, "index.json5");

function isChapterDir(name) {
    return /^chapter-\d+$/.test(name);
}

function isPageFile(name) {
    return /^\d+\.json5$/.test(name);
}

function findMissingPages(pages) {
    if (!pages.length) return [];

    const missing = [];
    const start = pages[0];
    const end = pages[pages.length - 1];

    for (let i = start; i <= end; i++) {
        if (!pages.includes(i)) missing.push(i);
    }

    return missing;
}

const chapters = {};
const chapterSummaries = [];

for (const entry of fs.readdirSync(ROOT, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    if (!isChapterDir(entry.name)) continue;

    const chapterPath = path.join(ROOT, entry.name);

    const pages = fs
        .readdirSync(chapterPath)
        .filter(isPageFile)
        .map(f => Number(f.replace(".json5", "")))
        .sort((a, b) => a - b);

    if (!pages.length) continue;

    chapters[entry.name] = pages;

    chapterSummaries.push({
        name: entry.name,
        pages,
    });
}


let output = `// AUTO-GENERATED FILE
// Do not edit manually
// Generated by build_index.js

{
  chapters: {
`;

for (const [chapter, pages] of Object.entries(chapters)) {
    output += `    "${chapter}": [${pages.join(", ")}],\n`;
}

output += `  }
}
`;

fs.writeFileSync(OUTPUT, output, "utf8");


console.log("\nindex.json5 generated");
console.log("Indexed pages:\n");

chapterSummaries.forEach((c, i) => {
    const isLastChapter = i === chapterSummaries.length - 1;
    const chapterPrefix = isLastChapter ? "└─" : "├─";
    const childPrefix = isLastChapter ? "   " : "│  ";

    const first = c.pages[0];
    const last = c.pages[c.pages.length - 1];
    const missing = findMissingPages(c.pages);

    console.log(
        ` ${chapterPrefix} ${c.name} (${c.pages.length} pages)`
    );
    if (missing.length) {
        console.log(
            ` ${childPrefix}├─ pages ${first}-${last}`
        );
    } else {
        console.log(
            ` ${childPrefix}└─ pages ${first}-${last}`
        );
    }

    if (missing.length) {
        console.log(
            ` ${childPrefix}└─ /!\ missing pages: ${missing.join(", ")}`
        );
    } else return
});

console.log("");
